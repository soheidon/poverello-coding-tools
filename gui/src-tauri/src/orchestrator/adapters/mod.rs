use super::types::{AgentRole, OrchestratorProfile};
use serde::{Deserialize, Serialize};
use std::path::PathBuf;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AdapterExecutionInput {
    pub role: AgentRole,
    pub profile: OrchestratorProfile,
    pub system_prompt: String,
    pub user_prompt: String,
    pub project_path: PathBuf,
    pub temperature: Option<f32>,
}

#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct NormalizedUsage {
    /// Number of input / prompt tokens processed by the model.
    pub input_tokens: Option<u64>,
    /// Number of output / completion tokens generated by the model.
    pub output_tokens: Option<u64>,
    /// Explicit total token count as reported by the provider.
    pub raw_total_tokens: Option<u64>,
    /// Tokens read from cache (prompt cache hit).
    pub cache_read_tokens: Option<u64>,
    /// Tokens written to cache (prompt cache creation).
    pub cache_write_tokens: Option<u64>,
}

impl NormalizedUsage {
    /// Computes backward-compatible tokens_used:
    /// Prioritizes raw_total_tokens if present.
    /// Otherwise, if both input_tokens and output_tokens are present, returns their checked_add.
    /// If either is missing, or if addition overflows, returns None.
    pub fn compute_tokens_used(&self) -> Option<u64> {
        if let Some(total) = self.raw_total_tokens {
            Some(total)
        } else if let (Some(inp), Some(out)) = (self.input_tokens, self.output_tokens) {
            inp.checked_add(out)
        } else {
            None
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AdapterExecutionOutput {
    pub content: String,
    pub raw_json: Option<String>,
    pub tokens_used: Option<u64>,
    pub model_used: String,
    pub duration_ms: u64,
    #[serde(skip_serializing, default)]
    pub usage: Option<NormalizedUsage>,
}
